    @Override
    public void periodic() {
        /*
         * Periodically try to apply the operator perspective.
         * If we haven't applied the operator perspective before, then we should apply it regardless of DS state.
         * This allows us to correct the perspective in case the robot code restarts mid-match.
         * Otherwise, only check and apply the operator perspective if the DS is disabled.
         * This ensures driving behavior doesn't change until an explicit disable event occurs during testing.
         */
        
        if (!m_hasAppliedOperatorPerspective || DriverStation.isDisabled()) {
            DriverStation.getAlliance().ifPresent(allianceColor -> {
                setOperatorPerspectiveForward(
                    allianceColor == Alliance.Red
                        ? kRedAlliancePerspectiveRotation
                        : kBlueAlliancePerspectiveRotation
                );
                m_hasAppliedOperatorPerspective = true;
            });
        }
        
        //limelight, deprecated
        if(LimelightHelpers.getTV(Constants.LIMELIGHT_NAME))
        {
             double latency = LimelightHelpers.getLatency_Capture(Constants.LIMELIGHT_NAME) + LimelightHelpers.getLatency_Pipeline(Constants.LIMELIGHT_NAME);
             double timestamp = Timer.getFPGATimestamp() - (latency / 1000.0);
        addVisionMeasurement(LimelightHelpers.getBotPose2d(Constants.LIMELIGHT_NAME), timestamp);
        }
        
        //Generated, theoretically fuses the two poses together
        Optional<EstimatedRobotPose> visionEst = visionEstimator.visionEstimationUpdate();

        visionEst.ifPresent(est -> {
            Pose2d visionPose = est.estimatedPose.toPose2d();
            double timestamp = est.timestampSeconds;  // PhotonVision-provided timestamp
            Matrix<N3, N1> stdDevs = visionEstimator.getEstimationStdDevs();

            // Add the vision measurement to the swerve Kalman filter
            addVisionMeasurement(visionPose, timestamp, stdDevs);
        });

        field.setRobotPose(getState().Pose.getX()+8,getState().Pose.getY()+4, getState().Pose.getRotation()); //Updates the field map with robot pose
        
    }

    private void startSimThread() {
        m_lastSimTime = Utils.getCurrentTimeSeconds();

        /* Run simulation at a faster rate so PID gains behave more reasonably */
        m_simNotifier = new Notifier(() -> {
            final double currentTime = Utils.getCurrentTimeSeconds();
            double deltaTime = currentTime - m_lastSimTime;
            m_lastSimTime = currentTime;

            /* use the measured time delta, get battery voltage from WPILib */
            updateSimState(deltaTime, RobotController.getBatteryVoltage());
        });
        m_simNotifier.startPeriodic(kSimLoopPeriod);
    }

