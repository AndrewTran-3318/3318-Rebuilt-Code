    public Pose2d getClosestHub()
    {
        if(distanceBetweenPoints(getState().Pose, Constants.RED_HUB_CORDS) < distanceBetweenPoints(getState().Pose, Constants.BLUE_HUB_CORDS))
        {
            return Constants.RED_HUB_CORDS;
        }
        else{
            return Constants.BLUE_HUB_CORDS;
        }
    }

    public double distanceBetweenPoints(Pose2d a, Pose2d b)
    {
        return Math.sqrt(
            Math.pow(a.getX()-b.getX(), 2) +
            Math.pow(a.getY()-b.getY(), 2)
        );
    }

